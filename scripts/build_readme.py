"""Generate README.md: what the catalog is, how it was built, and where to browse it.

The prose comes from data/about.yaml, which the site's About page also renders, and the
numbers from scripts/counts.py, which the site build also uses. The README lists only the
featured entries and points to the website for everything else.

Usage:
    uv run scripts/build_readme.py
"""

from __future__ import annotations

from datetime import date

import yaml

from common import ROOT
from counts import REPO, SITE, catalog_counts, fill, load_terms
from validate import load_entries


def md_link_rows(rows: list[dict]) -> str:
    return "\n".join(f"| [`{r['path']}`]({r['path']}) | {r['text']} |" for r in rows)


def main() -> None:
    entries = load_entries()
    terms = load_terms()
    taxonomy = yaml.safe_load((ROOT / "taxonomy" / "constructs.yaml").read_text())
    n = catalog_counts(entries, terms, taxonomy)
    about = fill(yaml.safe_load((ROOT / "data" / "about.yaml").read_text()), n)
    featured = sorted((e for e in entries.values() if e.get("featured")), key=lambda e: (-e["year"], e["name"].lower()))

    steps = "\n".join(f"{i}. **{s['title']}.** {s['text']}" for i, s in enumerate(about["built"]["steps"], 1))
    uses = []
    for u in about["use"]:
        uses.append(f"- **{u['title']}.** {u['text']}")
        if u.get("code"):
            uses.append("\n  ```\n" + "\n".join(f"  {c}" for c in u["code"]) + "\n  ```\n")
    not_for = "\n".join(f"- **{x['title']}** {x['text']}" for x in about["not_for"])
    gaps = "\n".join(f"- {g}" for g in about["gaps"])

    out = f"""<!-- Generated by scripts/build_readme.py from data/about.yaml and the catalog. Edit those, not this file. -->

<p align="center"><img src="site/src/logo.svg" width="64" height="64" alt=""></p>
<h1 align="center">awesome health ai evals</h1>
<p align="center">{about['tagline']}</p>
<p align="center"><a href="{SITE}"><b>Browse the catalog</b></a> &nbsp;·&nbsp; <a href="{SITE}/#/constructs">Constructs</a> &nbsp;·&nbsp; <a href="{SITE}/#/glossary">Glossary</a> &nbsp;·&nbsp; <a href="{SITE}/#/about">About</a></p>

## What's inside

{chr(10).join(f"- {w}" for w in about['what'])}

{about['caveat']}

## How the catalog was built

```mermaid
flowchart LR
  A["Search<br>OpenAlex, paperclip,<br>Hugging Face, GitHub"] --> B["{n['screened']:,} titles and<br>abstracts screened"]
  B --> C["Two LLM screening passes<br>{n['kept']:,} kept"]
  C --> D["Merged and read in full<br>{n['candidates']:,} candidates"]
  D --> E["{n['entries']:,} entries"]
  E --> F["{n['terms']:,} scoring terms<br>copied from sources"]
  F --> G["Clustered, then a proposer and<br>a challenger agent drafted constructs"]
  G --> H["{n['constructs']} constructs<br>in {n['domains']} domains"]
  E --> I["Website, README<br>and skills"]
  H --> I
```

{about['built']['intro']}

{steps}

{about['built']['outro']}

## Start here

Widely used benchmarks and ones built in low- and middle-income countries. Everything else is on the [website]({SITE}/#/catalog).

{chr(10).join(f"- [{e['name']}]({SITE}/#/e/{e['id']}) ({e['year']}). {e['summary']}" for e in featured)}

## Use it

{chr(10).join(uses)}

## Repository layout

| Path | What's there |
|---|---|
{md_link_rows(about['layout'])}

## How not to use it

{not_for}

## Known gaps

{gaps}

## Contributing

{about['contributing']}

## License

{about['license']}

_Last built {date.today().isoformat()}._
"""
    (ROOT / "README.md").write_text(out)
    print(f"README.md: {n['entries']} entries, {len(featured)} featured")


if __name__ == "__main__":
    main()
