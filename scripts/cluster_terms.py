"""Cluster the pass-2 evaluation terms into candidate constructs (taxonomy step 1).

Embeds each term with its definition (OpenAI text-embedding-3-small; cached in
search/work/term_embeddings.npz, so re-runs embed only new text), clusters them
by average-linkage cosine distance, and writes:

- taxonomy/terms.jsonl: every term instance with its cluster;
- taxonomy/clusters.yaml: clusters by size, with the most common term names and
  sample definitions;
- search/work/cluster_digest.txt: a compact view of the clusters for the proposer
  and challenger agents (multi-entry clusters in full, singletons one per line).

Usage:
    uv run scripts/cluster_terms.py [--threshold 0.45]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from collections import Counter, defaultdict

import numpy as np
import yaml
from openai import OpenAI
from scipy.cluster.hierarchy import fcluster, linkage

from common import ROOT, WORK, load_env, load_yaml

CACHE = WORK / "term_embeddings.npz"
MODEL = "text-embedding-3-small"


def collect() -> list[dict]:
    rows = []
    for path in sorted((ROOT / "terms").glob("*.yaml")):
        doc = load_yaml(path.read_text()) or {}
        for t in doc.get("terms") or []:
            rows.append({"entry": path.stem, "term": str(t["term"]).strip(), "level": t.get("level"),
                         "parent": t.get("parent"), "definition": str(t.get("definition") or "").strip(),
                         "verbatim": t.get("definition_verbatim", True)})
    return rows


def text_of(r: dict) -> str:
    return f"{r['term']}. {r['definition'][:400]}"


def embed(texts: list[str]) -> np.ndarray:
    cache = {}
    if CACHE.exists():
        z = np.load(CACHE, allow_pickle=False)
        cache = dict(zip(z["keys"].tolist(), z["vecs"]))
    keys = [hashlib.sha1(t.encode()).hexdigest() for t in texts]
    todo = sorted({k: t for k, t in zip(keys, texts) if k not in cache}.items())
    if todo:
        load_env()
        client = OpenAI(api_key=os.environ["OPENAI_API_KEY"])
        for i in range(0, len(todo), 500):
            chunk = todo[i:i + 500]
            resp = client.embeddings.create(model=MODEL, input=[t for _, t in chunk])
            for (k, _), d in zip(chunk, resp.data):
                cache[k] = np.array(d.embedding, dtype=np.float32)
        np.savez(CACHE, keys=np.array(list(cache)), vecs=np.stack(list(cache.values())))
        print(f"embedded {len(todo)} new texts", file=sys.stderr)
    return np.stack([cache[k] for k in keys])


def write_digest(clusters: list[dict]) -> None:
    lines = ["# Cluster digest: clusters spanning 2+ entries (names, 2 definitions); singletons one per line.", ""]
    for c in clusters:
        if c["entries"] >= 2:
            lines.append(f"{c['id']} | {c['entries']} entries, {c['terms']} terms | " + "; ".join(c["names"]))
            lines += ["    - " + d for d in c["sample_definitions"][:2]]
    lines += ["", "## Singleton clusters (id | names)", ""]
    lines += [f"{c['id']} | " + "; ".join(c["names"][:3]) for c in clusters if c["entries"] < 2]
    (WORK / "cluster_digest.txt").write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--threshold", type=float, default=0.45)
    args = parser.parse_args()

    rows = collect()
    X = embed([text_of(r) for r in rows])
    X /= np.linalg.norm(X, axis=1, keepdims=True)
    labels = fcluster(linkage(X, method="average", metric="cosine"), t=args.threshold, criterion="distance")

    groups = defaultdict(list)
    for r, lab in zip(rows, labels):
        groups[int(lab)].append(r)
    ordered = sorted(groups.values(), key=lambda g: (-len({r["entry"] for r in g}), -len(g)))
    clusters, out_rows = [], []
    for i, g in enumerate(ordered, 1):
        cid = f"k{i:03d}"
        names = Counter(r["term"] for r in g)
        defs = [r for r in g if r["definition"] and r["verbatim"]] or [r for r in g if r["definition"]]
        clusters.append({
            "id": cid, "terms": len(g), "entries": len({r["entry"] for r in g}),
            "names": [n for n, _ in names.most_common(10)],
            "sample_definitions": [f"{r['term']} ({r['entry']}): {r['definition'][:220]}" for r in defs[:3]],
        })
        out_rows += [{**r, "cluster": cid} for r in g]

    tax = ROOT / "taxonomy"
    tax.mkdir(exist_ok=True)
    with (tax / "terms.jsonl").open("w") as f:
        for r in out_rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    header = (f"# Generated by scripts/cluster_terms.py (threshold {args.threshold}): {len(rows)} terms from "
              f"{len({r['entry'] for r in rows})} entries in {len(clusters)} clusters, largest first.\n")
    (tax / "clusters.yaml").write_text(header + yaml.safe_dump(clusters, sort_keys=False, allow_unicode=True, width=140))
    write_digest(clusters)
    sizes = Counter(min(c["entries"], 10) for c in clusters)
    print(f"{len(rows)} terms -> {len(clusters)} clusters; clusters by entry count (10 = 10+): "
          f"{sorted(sizes.items())}", file=sys.stderr)


if __name__ == "__main__":
    main()
