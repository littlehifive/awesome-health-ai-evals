"""Build data/related.yaml (guidance and surveys) from the screening decisions.

Lists every record whose decision is related_guidance or survey, most cited
first. Hand edits to data/related.yaml are lost on re-run; put corrections in
data/related_overrides.yaml instead ({drop: [record ids], add: {guidance: [...], surveys: [...]}}).

Usage:
    uv run scripts/build_related.py
"""

from __future__ import annotations

import sys

import yaml

from common import ROOT, WORK, read_jsonl
from screen import latest_decisions

SECTIONS = {"related_guidance": "guidance", "survey": "surveys"}


def url_of(r: dict) -> str | None:
    if r["doi"]:
        return f"https://doi.org/{r['doi']}"
    if r["arxiv_id"]:
        return f"https://arxiv.org/abs/{r['arxiv_id']}"
    return r["url"]


def main() -> None:
    decisions = latest_decisions()
    overrides_path = ROOT / "data" / "related_overrides.yaml"
    overrides = yaml.safe_load(overrides_path.read_text()) if overrides_path.exists() else {}
    drop = set(overrides.get("drop") or [])

    out = {"guidance": [], "surveys": []}
    for r in read_jsonl(WORK / "records.jsonl"):
        d = decisions.get(r["id"])
        if not d or d["label"] not in SECTIONS or r["id"] in drop or not url_of(r):
            continue
        out[SECTIONS[d["label"]]].append({
            "title": " ".join(r["title"].split()),
            "url": url_of(r),
            "year": r["year"],
            "by": r["venue"],
            "cited_by": r["cited_by"] or 0,
            "record": r["id"],
        })
    for key, items in out.items():
        items += (overrides.get("add") or {}).get(key) or []
        items.sort(key=lambda x: (-(x.get("cited_by") or 0), x["title"].lower()))

    header = ("# Generated by scripts/build_related.py from search/screening.csv. Don't edit by hand;\n"
              "# put corrections in data/related_overrides.yaml.\n")
    (ROOT / "data" / "related.yaml").write_text(
        header + yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=120))
    print(f"data/related.yaml: {len(out['guidance'])} guidance, {len(out['surveys'])} surveys", file=sys.stderr)


if __name__ == "__main__":
    main()
